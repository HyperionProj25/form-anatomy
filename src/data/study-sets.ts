/** Part ids for a set: the right side of bilateral structures, midline parts as they are. */
export function studySetIds(set: StudySet): string[] {
  return set.keys
    .map((k) => partForSide(k, "right") ?? partsByKey(k)[0])
    .filter((p): p is NonNullable<typeof p> => !!p)
    .map((p) => p.id);
}
